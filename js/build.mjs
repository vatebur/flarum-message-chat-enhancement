import { mkdir, readFile, writeFile } from 'node:fs/promises';

const groups = JSON.parse(await readFile(new URL('../style-groups.json', import.meta.url), 'utf8'));
const source = await readFile(new URL('./src/admin.js', import.meta.url), 'utf8');

await mkdir(new URL('./dist/', import.meta.url), { recursive: true });
await writeFile(
  new URL('./dist/admin.js', import.meta.url),
  `// Generated by js/build.mjs.\nmodule.exports = (${source.trim()})(${JSON.stringify(groups, null, 2)});\n`
);

const forum = await readFile(new URL('./src/forum.js', import.meta.url), 'utf8');
await writeFile(
  new URL('./dist/forum.js', import.meta.url),
  `// Generated by js/build.mjs.\nmodule.exports = (${forum.trim()})();\n`
);
